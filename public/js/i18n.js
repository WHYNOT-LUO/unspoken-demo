export const STRINGS = { zh, en };
export const LANGS = ["zh", "en"];

let current = "zh";

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : "zh";
}

export function getLang() {
  return current;
}

export function t(key, vars = {}) {
  const s = STRINGS[current][key] ?? STRINGS.zh[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

/** Default language: what the visitor chose before, else the browser's language. */
export function detectLang(saved, browserLangs = []) {
  if (LANGS.includes(saved)) return saved;
  const first = (browserLangs[0] || "").toLowerCase();
  return first.startsWith("zh") ? "zh" : first ? "en" : "zh";
}
